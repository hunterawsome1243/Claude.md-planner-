const { launch, open, check, mockDoc } = require('./lib');
const fa = (pg) => pg.evaluate(() => { const e = document.activeElement; return e ? e.tagName + (e.id ? '#' + e.id : '') + (e.name ? '{' + e.name + '=' + e.value + '}' : '') + (e.dataset.act ? '[' + e.dataset.act + ']' : '') : null; });
(async () => {
  const b = await launch();
  const { pg, errs, ctx } = await open(b, 'mocked.html');
  await pg.click('[data-act="new-project"] >> visible=true');
  await pg.fill('#np-name', 'Recipe Box');
  await pg.check('input[name="np-starter"][value="web"]');
  await pg.click('[data-act="create"]');
  await pg.waitForTimeout(300);
  // from the prompt dialog
  await pg.click('.next [data-act="prompt"]');
  const btns = await pg.$$eval('.modal-actions button', (e) => e.map((x) => x.textContent.trim()));
  check('prompt dialog offers Log how it went', btns.join('|') === 'Close|Log how it went|Sharpen with Claude|Copy prompt', btns);
  await pg.click('#modal-root [data-act="log-session"]');
  check('session dialog replaces it, focus on the outcome', (await pg.textContent('#m-title')) === 'Log a session' && (await fa(pg)) === 'INPUT{ss-outcome=done}', await fa(pg));
  const sel = await pg.inputValue('#ss-task');
  const d0 = await mockDoc(pg, 'Recipe Box');
  check('task preselected', sel === d0.milestones[0].id + ':' + d0.milestones[0].tasks[0].id, sel);
  await pg.check('input[name="ss-outcome"][value="partly"]');
  await pg.fill('#ss-summary', 'Created the project. npm test fails because vitest is missing.');
  await pg.fill('#ss-wrong', 'It also edited README');
  await pg.fill('#ss-rule', 'Only change the files the task names');
  await pg.click('[data-act="save-session"]');
  await pg.waitForTimeout(1500);
  const d1 = await mockDoc(pg, 'Recipe Box');
  check('session stored', d1.sessions.length === 1 && d1.sessions[0].outcome === 'partly' && /vitest is missing/.test(d1.sessions[0].summary) && d1.sessions[0].task === d1.milestones[0].tasks[0].title, d1.sessions);
  check('task now in progress', d1.milestones[0].tasks[0].status === 'doing');
  check('lesson added from what went wrong', d1.lessons.length === 1 && d1.lessons[0].happened === 'It also edited README' && d1.lessons[0].change === 'Only change the files the task names', d1.lessons);
  check('focus back on the prompt button', /prompt/.test(await fa(pg)), await fa(pg));
  const toast = await pg.textContent('#toast');
  check('toast', /Session logged\. ".*" is now in progress\. A lesson with your rule was added/.test(toast), toast);
  // from Next up, with Claude follow-ups
  await pg.click('.next [data-act="log-session"]');
  await pg.fill('#ss-summary', 'Added the empty state.');
  await pg.click('[data-act="save-session-ai"]');
  await pg.waitForTimeout(100);
  check('working banner with Stop', /Claude is reading the session/.test(await pg.textContent('.modal')), null);
  check('the dialog stays open while Claude works (Escape stops Claude, round 72)', !!(await pg.$('.modal')));
  await pg.waitForTimeout(600);
  const items = await pg.$$eval('.prop-list li', (e) => e.map((x) => x.textContent.replace(/\s+/g, ' ').trim()));
  check('suggestions: 2 tasks + rule', items.length === 3 && /Run npm test before saying a task is done/.test(items[2]) && !/^- /.test(items[2]), items);
  check('focus on the heading of Claude\'s list (round 45)', (await fa(pg)) === 'H3#fu-h', await fa(pg));
  await pg.click('[data-act="session-pick"][data-k="t1"]');
  check('count updates', (await pg.textContent('[data-act="session-accept"]')) === 'Add 1 task and the rule');
  await pg.click('[data-act="session-accept"]');
  await pg.waitForTimeout(1500);
  const d2 = await mockDoc(pg, 'Recipe Box');
  const titles = d2.milestones[0].tasks.map((t) => t.title);
  check('follow-up inserted right after the task', titles[1] === 'Add error message for empty list' && titles.length === 5, titles);
  check('rule appended to conventions', /- Run npm test before saying a task is done$/.test(d2.conventions), d2.conventions);
  check('task done', d2.milestones[0].tasks[0].status === 'done');
  // Improve tab list
  await pg.click('#tab-improve');
  const head = await pg.textContent('.panel-head:has(h2:text("Sessions")) p');
  check('stats line', head === '2 logged: 1 done, 1 partly done, 0 stuck.', head);
  const rows = await pg.$$eval('.session', (e) => e.map((x) => x.textContent.replace(/\s+/g, ' ').trim()));
  check('newest first', /Done/.test(rows[0]) && /Partly done/.test(rows[1]), rows);
  await pg.click('[data-act="del-session"] >> nth=0');
  await pg.waitForTimeout(100);
  check('delete with undo', (await pg.$$('.session')).length === 1 && /Session deleted/.test(await pg.textContent('#toast')));
  await pg.click('#toast [data-act="undo"]');
  check('undo restores', (await pg.$$('.session')).length === 2);
  // stop during follow-ups
  await pg.click('#sheet [data-act="log-session"]');
  if (await pg.$('#ss-task option[value=""]')) await pg.selectOption('#ss-task', await pg.$eval('#ss-task option:not([disabled])', (o) => o.value)); // nothing to go on: choose the first task
  await pg.evaluate(() => { window.__SAMPLE_DELAY__ = 2000; });
  await pg.click('[data-act="save-session-ai"]');
  await pg.waitForTimeout(200);
  await pg.click('[data-act="stop-followups"]');
  await pg.waitForTimeout(200);
  check('stopped message, session kept', /Stopped\. The session is saved\./.test(await pg.textContent('.modal')), await pg.textContent('.modal .empty-note'));
  await pg.click('[data-act="close-modal"]');
  await pg.waitForTimeout(1500);
  const d3 = await mockDoc(pg, 'Recipe Box');
  check('three sessions', d3.sessions.length === 3, d3.sessions.length);
  console.log('errors', errs);
  await ctx.close();
  // plain page: no Claude button, empty project
  const o = await open(b, 'plain.html');
  await o.pg.click('[data-act="new-project"] >> visible=true');
  await o.pg.fill('#np-name', 'Empty');
  await o.pg.click('[data-act="create"]');
  await o.pg.click('#tab-improve');
  await o.pg.click('#sheet [data-act="log-session"]');
  check('no tasks: the form opens on "Something else" (round 9)', (await o.pg.inputValue('#ss-task')) === 'other' && await o.pg.isVisible('#ss-what'));
  await o.pg.keyboard.press('Escape');
  console.log('errors', o.errs);
  await b.close();
})();
